using System.Text.RegularExpressions;

namespace Csms.Infrastructure.Documents;

/// <summary>
/// Детерминированная нормализация глаголов и объектов для дедупликации.
/// Словарь ручной и конечный: если формы нет в списке, строка остаётся как есть
/// и сравнение идёт по ней — модель не может «догадаться» за код.
/// </summary>
public static class DocumentFunctionNormalizer
{
