        ["разместит"] = "разместить",
        ["вправе"] = "вправе",
        ["может"] = "может",
    };

    public static string Whitespace(string value) =>
        Regex.Replace(value ?? string.Empty, @"\s+", " ").Trim();

    public static string Compare(string value)
    {
        var text = Whitespace(value)
            .ToLowerInvariant()
            .Replace('ё', 'е');
        return Regex.Replace(text, @"[^\p{L}\p{N}]+", " ").Trim();
    }

    public static string ToInfinitive(string verb)
    {
        var key = Compare(verb).Replace(" ", string.Empty);
        return VerbForms.TryGetValue(key, out var infinitive) ? infinitive : key;
    }

    public static string Object(string value) => Compare(value);

    public static bool ContainsNormalized(string text, string fragment)
    {
        var normalizedText = Compare(text);
        var normalizedFragment = Compare(fragment);
        return normalizedFragment.Length > 0 && normalizedText.Contains(normalizedFragment, StringComparison.Ordinal);
    }
}
