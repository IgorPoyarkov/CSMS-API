namespace Csms.Domain;

/// <summary>
/// Состояние пакета сведений в обмене с ЕИС.
///
/// Значения идут по порядку жизненного цикла, но переходить «по номеру» нельзя:
/// каждый шаг разрешён только методом <see cref="EisPackage"/> и только из
/// допустимого статуса. Так «отправить неподписанное» или «принять без ответа
/// ЕИС» не получится даже по ошибке в вызывающем коде.
/// </summary>
public enum EisPackageStatus
{
    /// <summary>Черновик: данные собраны, подписи нет.</summary>
    Draft = 0,

    /// <summary>Идёт подписание: фронт подписывает содержимое и присылает подпись.</summary>
    Signing = 1,

    /// <summary>Подпись приложена и сверена с содержимым пакета.</summary>
    Signed = 2,

    /// <summary>Пакет передан в транспорт ЕИС, ждём ответа шлюза.</summary>
    SentToEis = 3,

    /// <summary>ЕИС приняла пакет и проверяет его форматно-логическим контролем.</summary>
    FlkChecking = 4,

    /// <summary>Пакет принят: документ зарегистрирован, есть <c>eisGuid</c>.</summary>
    AcceptedInLk = 5,

    /// <summary>ФЛК вернула ошибки: пакет надо исправить и отправить заново.</summary>
    RejectedByFlk = 6,

    /// <summary>Транспортная ошибка: до ЕИС не дошли, отправку можно повторить.</summary>
    SendFailed = 7,
}
